@SecurityScheme(
        name = "bearerAuth",
        type = SecuritySchemeType.HTTP,
        scheme = "bearer",
        bearerFormat = "JWT",
        description = "Enter the JWT access token without the Bearer prefix. Swagger UI adds it automatically."
)
public class OpenApiConfig {
}
